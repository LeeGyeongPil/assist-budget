"""Prompt profiles: how each Home Assistant release builds the Assist system prompt.

The prompt strings are in ``data/prompts.json`` (extracted from HA sources by
``tools/fixtures/extract_prompts.py``). Only HA 2026.11.x is verified byte for
byte against output generated by a real HA; the other profiles are built from
the released source and reported as "unverified profile".
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from importlib import resources

from . import EXIT_UNSUPPORTED
from .errors import AssistBudgetError
from .storage import Warn

STATIC_HEADER = "Static Context: An overview of the areas and the devices in this smart home:"
AREA_PROMPT = (
    "When a user asks to turn on all devices of a specific type, "
    "ask the user to specify an area, unless there is only one device of that type."
)
NO_TIMER_PROMPT = "This device is not able to start timers."

# Lowest and highest HA release a profile exists for.
MIN_SUPPORTED = (2025, 5)
LAST_KNOWN = (2026, 11)
LEGACY_LAST = (2026, 7)
VERIFIED_FROM = (2026, 11)


@dataclass(frozen=True)
class Profile:
    """Prompt pieces of one HA release family."""

    name: str
    verified: bool
    default_instructions: str
    dynamic_prompt: str
    no_entities_prompt: str
    control_prompt: str
    legacy_layout: bool  # 2025.5-2026.7: one AssistAPI prompt; 2026.8+: homeassistant + intent platforms


def _load() -> dict[str, dict[str, str]]:
    text = resources.files("assist_budget").joinpath("data", "prompts.json").read_text(encoding="utf-8")
    return json.loads(text)


def parse_version(text: str) -> tuple[int, int]:
    """Return ``(year, month)`` from a HA version such as ``2026.11.3`` or ``2026.12.0b1``."""
    match = re.match(r"\s*(\d{4})\.(\d{1,2})(?:\.|$|[a-z])", text or "")
    if not match:
        raise AssistBudgetError("err_bad_version", version=text)
    return int(match.group(1)), int(match.group(2))


def _profile(name: str, verified: bool, legacy: bool) -> Profile:
    data = _load()["2025.5-2026.7" if legacy else "2026.8+"]
    return Profile(
        name=name,
        verified=verified,
        default_instructions=data["DEFAULT_INSTRUCTIONS_PROMPT"],
        dynamic_prompt=data["DYNAMIC_CONTEXT_PROMPT"],
        no_entities_prompt=data["NO_ENTITIES_PROMPT"],
        control_prompt=data["DEVICE_CONTROL_TOOL_USAGE_PROMPT"],
        legacy_layout=legacy,
    )


def select_profile(version: str) -> tuple[Profile, list[Warn]]:
    """Pick the profile for a HA version. Raises exit code 3 below 2025.5."""
    ym = parse_version(version)
    if ym < MIN_SUPPORTED:
        raise AssistBudgetError("err_unsupported_version", EXIT_UNSUPPORTED, version=version)
    if ym <= LEGACY_LAST:
        profile = _profile("2025.5-2026.7", False, True)
        return profile, [("warn_unverified_profile", {"version": version, "profile": profile.name})]
    if ym < VERIFIED_FROM:
        profile = _profile("2026.8-2026.10", False, False)
        return profile, [("warn_unverified_profile", {"version": version, "profile": profile.name})]
    profile = _profile("2026.11", True, False)
    if ym > LAST_KNOWN:
        return profile, [("warn_newer_version", {"version": version, "profile": profile.name})]
    return profile, []
